package com.slayerledger.sync;

import net.runelite.client.config.Config;
import net.runelite.client.config.ConfigGroup;
import net.runelite.client.config.ConfigItem;

@ConfigGroup(SlayerLedgerConfig.GROUP)
public interface SlayerLedgerConfig extends Config
{
 String GROUP = "slayerledger-sync";
 @ConfigItem(keyName="enabled", name="Enable private Slayer sync", position=0,
  description="Sends only your character name, Slayer task/location/count, points, counters and modifier to Slayer Ledger over HTTPS. Disabled by default.",
  warning="This feature submits your IP address to a 3rd-party server not controlled or verified by RuneLite developers")
 default boolean enabled() { return false; }
 @ConfigItem(keyName="character", name="Paired character name", position=1,
  description="Exact OSRS display name paired on Slayer Ledger. Other logged-in characters are never sent.")
 default String character() { return ""; }
 @ConfigItem(keyName="writeKey", name="Slayer Ledger write key", position=2, secret=true,
  description="Paste the write key generated by Slayer Ledger. This is not a Jagex password or a Group Ironmen token.")
 default String writeKey() { return ""; }
}
